"""Add batch size and per-pass item order to run files saved before passes were logged.

No model calls. The order is reconstructed from the code that produced each pass:
  - stored ("current") passes, greedy and sampled: dataset order test-0..test-N, the order
    Runner.outputs sends missing items in (pipeline.py at 5ae0f29 / 1f004b2).
  - sampled reruns (E2/E4): generated with the original runs, before fc8280a added the
    shuffle, so also dataset order (with their own sampling seeds).
  - greedy reruns (E1/E3): generated by rerun_greedy.py after fc8280a, so shuffled with
    random.Random(f"{seed}-{prompt hash}").
Batch size is DRIFT_BATCH's default (64); the Kaggle commands in the README do not set it.
E3 reuses E1's text and E4 reuses E2's, so each prompt has four passes, not eight.
This assumes each pass generated all items in one call (no session resumed mid-pass).
Only measurement-step passes on the eval split are listed; they are the ones the tables use.

Usage: python backfill_batch_layout.py 1 2 3 4 5
"""
import json
import random
import sys

from drift import config
from drift.pipeline import phash, run_path

BATCH = 64
seeds = [int(a) for a in sys.argv[1:]] or config.SEEDS
for s in seeds:
    path = run_path(s)
    run = json.load(open(path))
    c = run["config"]
    if c.get("passes") and not c.get("passes_reconstructed"):
        print(f"seed {s}: passes were logged at run time, leaving them alone")
        continue
    n = c["n_eval"]
    passes = []
    for h, text in run["prompts"].items():
        assert phash(text) == h
        shuffled = list(range(n))
        random.Random(f"{s}-{h}").shuffle(shuffled)
        for decoding, envs in (("greedy", ["E1", "E3"]), ("sample", ["E2", "E4"])):
            for tag in ("current", "rerun"):
                order = shuffled if (tag == "rerun" and decoding == "greedy") else list(range(n))
                passes.append({"prompt": h, "env": envs[0], "used_by": envs, "tag": tag,
                               "split": "test", "batch_size": BATCH, "order": order})
    c["batch_size"] = BATCH
    c["rerun_order"] = "greedy reruns (E1/E3) shuffled; sampled reruns (E2/E4) dataset order"
    c["passes"] = passes
    c["passes_reconstructed"] = ("Reconstructed from code by backfill_batch_layout.py, not "
                                 "logged at run time; see that script for the assumptions.")
    json.dump(run, open(path, "w"))
    print(f"seed {s}: {len(passes)} passes written")

